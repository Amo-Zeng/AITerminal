'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const os = require('os');
const { fork } = require('child_process');
const { PluginManager } = require('../lib/pluginManager');
const { PluginRuntime, hostEnvironment } = require('../lib/pluginRuntime');
test('standard MCP stdio initialization, typed tool call, resource read and cleanup use the plugin host', async t => {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'ait-mcp-'));
    const manager = new PluginManager({ filePath: path.join(root, 'plugins.json') });
    const manifest = { schemaVersion: 2, id: 'fixture.mcp', name: 'MCP fixture', version: '1.0.0', description: 'MCP fixture', author: 'test', license: 'Apache-2.0', runtime: 'mcp', engines: { aiterminal: '>=1.4.0', pluginApi: '^1.0.0' }, permissions: ['mcp.connect'], mcp: { transport: 'stdio', command: process.execPath, args: [path.resolve('test/fixtures/pluginMcpServer.js')] } };
    manager.install(manifest, 'file:fixture');
    const owner = { pluginIds: new Set([manifest.id]) };
    const calls = [];
    const runtime = new PluginRuntime({ manager, owned: () => true, service: async (_owner, method) => { calls.push(method); return true; }, launch: () => fork(path.resolve('lib/pluginHost.js'), [], { env: hostEnvironment(), stdio: ['ignore', 'pipe', 'pipe', 'ipc'] }) });
    t.after(async () => { runtime.close(); await new Promise(resolve => setTimeout(resolve, 1500)); fs.rmSync(root, { recursive: true, force: true }); });
    const instance = await runtime.ensure(owner, manifest.id);
    const tool = instance.info.tools.find(item => item.title === 'echo_input');
    assert.match(tool.id, /^mcp-[0-9a-f]+$/);
    const result = await runtime.invoke(owner, manifest.id, 'tool', tool.id, { text: 'MCP 中文' });
    assert.equal(result.content[0].text, 'MCP 中文');
    await assert.rejects(runtime.invoke(owner, manifest.id, 'tool', tool.id, { invalid: true }), /参数/);
    const resources = await runtime.invoke(owner, manifest.id, 'tool', 'resource-list');
    assert.equal(resources.resources[0].uri, 'fixture://document');
    const resource = await runtime.invoke(owner, manifest.id, 'tool', 'resource-read', { uri: 'fixture://document' });
    assert.equal(resource.contents[0].text, 'resource fixture');
    assert.deepEqual(calls, ['mcp.start']);
});
